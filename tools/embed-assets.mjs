// Regenerates assets/embedded.js so the generator can export PNGs even when
// index.html is opened straight from disk (file://), where browsers block
// reading local images and fonts back into a canvas.
//
// Run from the project folder after replacing any logo or the font:
//   node tools/embed-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const toDataUrl = (rel, mime) =>
  `data:${mime};base64,${readFileSync(join(root, rel)).toString('base64')}`;

const data = {
  event: toDataUrl('assets/event-logo.png', 'image/png'),
  council: toDataUrl('assets/council-logo.png', 'image/png'),
  faruma: toDataUrl('fonts/Faruma.ttf', 'font/ttf'),
};

writeFileSync(
  join(root, 'assets/embedded.js'),
  `// Generated by tools/embed-assets.mjs. Do not edit by hand.\nwindow.EMBEDDED = ${JSON.stringify(data)};\n`
);
console.log('Wrote assets/embedded.js');
